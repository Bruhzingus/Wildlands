import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';

// Pin the source so learnset changes are explicit and reproducible.
const commit='227b573712414a86ba299d322fa398fbb2893edc';
const base=`https://raw.githubusercontent.com/PokeAPI/pokeapi/${commit}/data/v2/csv/`;
const cache=new URL('../artifacts/learnset-source/',import.meta.url);
await mkdir(cache,{recursive:true});
async function csv(name){
 const path=new URL(name,cache);let content;
 try{content=await readFile(path,'utf8');}catch{
  const response=await fetch(base+name);if(!response.ok)throw Error(`${name}: ${response.status}`);
  content=await response.text();await writeFile(path,content);
 }
 return content;
}
const [moves,learnsets]=await Promise.all([csv('moves.csv'),csv('pokemon_moves.csv')]);
const catalogue=new Set([...((await readFile(new URL('../src/data/moves.ts',import.meta.url),'utf8')).matchAll(/move\(\{id:'([^']+)'/g))].map(match=>match[1]));
const names=new Map(moves.trim().split('\n').slice(1).map(row=>{const [id,name]=row.split(',');return [+id,name];}));
const species=Object.fromEntries(Array.from({length:151},(_,index)=>[index+1,new Set()]));
for(const row of learnsets.trim().split('\n').slice(1)){
 const [id,,moveId,method]=row.split(',').map(Number),name=names.get(moveId);
 // Level-up, egg, tutor and TM moves from main-series versions; never a type-based guess.
 if(id<=151&&species[id]&&[1,2,3,4].includes(method)&&catalogue.has(name))species[id].add(name);
}
const rows=Object.entries(species).map(([id,names])=>` ${id}:${JSON.stringify([...names].sort())},`).join('\n');
await writeFile(new URL('../src/data/learnsets.ts',import.meta.url),`/** Generated by scripts/sync-learnsets.mjs from PokeAPI ${commit}.\n * Union of main-series level-up, egg, tutor and TM learnsets; run-level gates are adapted.\n * Source: ${base}pokemon_moves.csv\n * SHA-256: ${createHash('sha256').update(learnsets).digest('hex')} */\nexport const SPECIES_LEARNSETS:Readonly<Record<number,readonly string[]>>={\n${rows}\n};\n`);
console.log(`Cached learnsets for 151 species and ${catalogue.size} implemented moves.`);
